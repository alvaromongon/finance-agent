/**
 * The watchlist in the engine's store (#140, spec #124): the entries as JSON written only by the engine, read back
 * strictly, and `watchlist.md` as the view generated from it.
 */
import { describe, it } from "node:test";
import assert from "node:assert/strict";
import yaml from "js-yaml";
import { parseTicker as tk } from "../ticker.js";
import { parseWatchlistBlock } from "../utils/vault-parser.js";
import { decodeStore, encodeStore, renderWatchlistView, type PortfolioStore } from "../utils/portfolio-json.js";
import type { WatchlistEntry } from "../types.js";

const entries = (): WatchlistEntry[] => [
  {
    ticker: tk("AMD"),
    currency: "USD",
    horizon: "short",
    asset_class: "equity",
    thesis: "Data-center share gains.",
    date: "2026-11-20",
  },
  {
    ticker: tk("AIR.PA"),
    currency: "EUR",
    horizon: "medium",
    thesis: "",
    name: "Airbus",
    market: "Euronext Paris",
    thesis_link: "[[tesis-airpa]]",
    date: "2026-10-01",
  },
];

const store = (over: Partial<PortfolioStore> = {}): PortfolioStore => ({
  silos: {},
  unmoved: [],
  pendingDecisions: [],
  resolvedRejections: [],
  ...over,
});

describe("the watchlist in the store text", () => {
  it("writes the entries and the list the store began with, and reads back what it wrote", () => {
    const seeded = store({ watchlist: entries(), startingWatchlist: entries().slice(1) });
    const text = encodeStore(seeded);
    assert.match(text, /"watchlist": \[/);
    assert.match(text, /"starting_watchlist": \[/);
    assert.deepEqual(decodeStore(text, "state/portfolio.json"), seeded);
  });

  it("keeps a store with no watchlist as one with none (the state is still watchlist.md)", () => {
    const text = encodeStore(store());
    assert.doesNotMatch(text, /watchlist/);
    const read = decodeStore(text, "state/portfolio.json");
    assert.equal(read.watchlist, undefined);
    assert.equal(read.startingWatchlist, undefined);
  });

  // eslint-disable-next-line @typescript-eslint/no-explicit-any -- the test edits a document of a shape it makes
  const mutate = (change: (doc: any) => void): string => {
    const doc = JSON.parse(encodeStore(store({ watchlist: entries(), startingWatchlist: [] })));
    change(doc);
    return JSON.stringify(doc);
  };
  const refuses = (text: string, pattern: RegExp): void =>
    assert.throws(() => decodeStore(text, "state/portfolio.json"), pattern);

  it("refuses what it cannot read whole, naming the file and the field", () => {
    refuses(
      mutate((d) => (d.watchlist[0].ticker = "TC|K")),
      /state\/portfolio\.json: watchlist\[0\]\.ticker/,
    );
    refuses(
      mutate((d) => (d.watchlist[1].currency = "GBP")),
      /watchlist\[1\]\.currency: must be EUR or USD/,
    );
    refuses(
      mutate((d) => (d.watchlist[0].horizon = "long")),
      /watchlist\[0\]\.horizon: must be short or medium/,
    );
    refuses(
      mutate((d) => (d.watchlist[0].asset_class = "bond")),
      /watchlist\[0\]\.asset_class: must be equity, commodity or etf/,
    );
    refuses(
      mutate((d) => (d.watchlist[0].date = "2026-02-30")),
      /watchlist\[0\]\.date: must be a calendar date/,
    );
    refuses(
      mutate((d) => (d.watchlist = "AMD")),
      /watchlist: must be a list/,
    );
    refuses(
      mutate((d) => (d.watchlist[1].thesis = 5)),
      /watchlist\[1\]\.thesis: must be text/,
    );
  });

  it("refuses a watchlist without the list the store began with, and the other way round", () => {
    refuses(
      mutate((d) => delete d.starting_watchlist),
      /starting_watchlist: is missing/,
    );
    refuses(
      mutate((d) => delete d.watchlist),
      /watchlist: is missing/,
    );
  });

  it("refuses the same ticker twice: a ticker is on the list once", () => {
    refuses(
      mutate((d) => (d.watchlist[1].ticker = "AMD")),
      /watchlist\[1\]\.ticker: AMD is already on the list/,
    );
  });
});

describe("watchlist.md, generated from the store", () => {
  it("is the file the old reader reads, with a note that it is generated", () => {
    const text = renderWatchlistView(store({ watchlist: entries(), startingWatchlist: [] }));
    assert.match(text, /^---\nschema_version: 1\n---\n/);
    assert.match(text, /Generated by the engine from `state\/portfolio\.json`: do not edit it/);
    const block = /```yaml\n([\s\S]*?)\n```/.exec(text)![1];
    const read = parseWatchlistBlock(block);
    assert.deepEqual(
      read.map((e) => [e.ticker, e.currency, e.horizon, e.thesis, e.date]),
      [
        ["AMD", "USD", "short", "Data-center share gains.", "2026-11-20"],
        ["AIR.PA", "EUR", "medium", "", "2026-10-01"],
      ],
    );
    assert.deepEqual(yaml.load(block), { watchlist: JSON.parse(JSON.stringify(read)) });
  });

  it("is an empty list when nothing is watched", () => {
    const text = renderWatchlistView(store({ watchlist: [], startingWatchlist: [] }));
    assert.match(text, /watchlist: \[\]/);
  });
});
